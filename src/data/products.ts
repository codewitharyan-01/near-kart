function build(): Product[] {
  const out: Product[] = [];
  let i = 0;
  for (const [shopId, rows] of Object.entries(ROWS)) {
    for (const r of rows) {
      i += 1;
      const [name, brand, category, emoji, packSize, mrp, price, stock, lowStockThreshold, gstRate, perishableDays] = r;
      out.push({
        id: `p${i}`,
        shopId,
        name,
        brand,
        category,
        emoji,
        packSize,
        mrp,
        price,
        gstRate,
        stock,
        lowStockThreshold,
        perishableDays,
        status: "active",
        popularity: Math.floor(Math.random() * 60) + (mrp < 50 ? 40 : 5),
        updateSource: "seed",
        lastUpdatedAt: Date.now(),
      });
    }
  }
  return out;
}

export const PRODUCTS: Product[] = build();

export function findProductByName(name: string) {
  return PRODUCTS.find((p) => p.name === name);
}
